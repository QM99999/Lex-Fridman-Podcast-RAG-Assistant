"""Step 6 - Evaluate RAG answer quality with an LLM-as-a-judge.

Follows the LLM Zoomcamp course (module 04) A->Q->A' setup:

    A  = original answer from the FAQ dataset (ground truth)
    Q  = question from the FAQ dataset
    A' = answer produced by our RAG pipeline (05_rag.answer)

A judge LLM (default gpt-5.6-luna, structured output) compares each A'
against A and decides whether the RAG answer conveys the same key information
("good") or is wrong / misses the key point ("bad"). Results are aggregated
per answer model so different answer models (e.g. gpt-4o-mini vs
deepseek-v4-flash) can be compared and the best one selected.

Optional query rewriting: with --rewrite llm (default), each question is
rewritten by an independent rewriter model (default gpt-4.1-nano) before
retrieval, so retrieval sees a clear self-contained question. The rewriter
is deliberately kept OUT of the answer-model list (and the judge), keeping
the bake-off fair: every answer model retrieves with the same rewritten
queries. Rewrites are cached per question hash in rewritten_queries.json.

The FAQ dataset is used ONLY as the evaluation benchmark (questions + ground
truth answers); it is not part of the retrieval knowledge base.

Incremental & resumable: results are checkpointed after every batch and
re-running skips (faq_id, answer_model) pairs that already have a score. The
checkpoint is invalidated only when backend / top_k / judge change (pass
--force to start fresh). Question count, sample size and the answer-model
list can change freely between runs - existing per-question results are
always reused, so a full run after a sampled run only evaluates the missing
questions.

Auto-switch: after the run, the best answer model (highest good rate; ties
broken by model name) is written to 05_MODEL in .env, so the app/CLI default
follows the evaluation. Disable with --no-set-default.

Configuration:
    06_JUDGE_MODEL   judge model (default: gpt-5.4-mini)
    05_MODEL         default answer model (default: gpt-4o-mini)
    OPENAI_API_KEY   required (judge; answer when provider=openai)
    DEEPSEEK_API_KEY required when an answer model is deepseek-*

Usage:
    python src/06_rag_eval.py                                   # full evaluation (all questions)
    python src/06_rag_eval.py --sample 100 --seed 42            # random sample across episodes
    python src/06_rag_eval.py --answer-models gpt-4o-mini,gpt-5.4-mini --judge-model gpt-5.6-luna
    python src/06_rag_eval.py --backend memory --top-k 3 --judge-model gpt-4o
"""

from __future__ import annotations

import argparse
import importlib
import json
import os
import random
import sys
import time
from collections import defaultdict
from concurrent.futures import ThreadPoolExecutor
from datetime import datetime, timezone
from pathlib import Path
from typing import Literal

from pydantic import BaseModel, Field
from tqdm import tqdm

sys.path.insert(0, str(Path(__file__).resolve().parent))
from retrieval import PROJECT_ROOT, rewrite_query  # noqa: E402
rag = importlib.import_module("05_rag")  # noqa: E402

DEFAULT_JUDGE_MODEL = "gpt-5.6-luna"
DEFAULT_ANSWER_MODEL = "gpt-5.4-mini"
DEFAULT_REWRITE_MODEL = "gpt-4.1-nano"
DEFAULT_REWRITE_CACHE = PROJECT_ROOT / "data/results" / "rewritten_queries.json"
BATCH = 8

class AnswerEvaluation(BaseModel):
    reasoning: str = Field(description="Reasoning about the quality of the answer.")
    score: Literal["good", "bad"] = Field(
        description="'good' if the answer is correct and complete, 'bad' otherwise.")


JUDGE_INSTRUCTIONS = """
You are an expert evaluator. You will be given:
1. A question from a student
2. The original answer from the podcast FAQ (ground truth)
3. An answer generated by an AI assistant

Your task is to decide if the AI answer is semantically equivalent to the
original answer.

Rules:
- The AI answer does NOT need to be word-for-word identical
- It should convey the same key information
- Extra detail is fine as long as the core answer is correct
- Mark 'bad' only if the AI answer is wrong or misses the key point

Be fair and focus on correctness, not style.
""".strip()

JUDGE_PROMPT = """
Question:
{question}

Original Answer (ground truth):
{answer_orig}

AI Answer:
{answer_llm}
""".strip()


def load_faq_records(faq_dir: str) -> list[dict]:
    """Load FAQ items as evaluation records: question + ground-truth answer."""
    records: list[dict] = []
    for f in sorted(Path(faq_dir).glob("*.faq.json")):
        data = json.loads(f.read_text(encoding="utf-8"))
        for i, qa in enumerate(data.get("faqs", []), 1):
            records.append({
                "faq_id": qa.get("id") or f"{data.get('episode')}-q{i}",
                "episode": data.get("episode"),
                "question": qa["question"],
                "answer": qa["answer"],
            })
    return records


def sample_records(records: list[dict], n: int, seed: int) -> list[dict]:
    """Stratified random sample: proportional per episode, reproducible via seed."""
    rng = random.Random(seed)
    by_episode: dict = defaultdict(list)
    for r in records:
        by_episode[r["episode"]].append(r)
    per: dict = {}
    for ep, rs in by_episode.items():
        per[ep] = round(len(rs) / len(records) * n)
    diff = n - sum(per.values())
    if diff:
        biggest = max(by_episode, key=lambda ep: len(by_episode[ep]))
        per[biggest] += diff
    sampled: list[dict] = []
    for ep, rs in by_episode.items():
        sampled.extend(rng.sample(rs, min(per[ep], len(rs))))
    rng.shuffle(sampled)
    print("sample: " + ", ".join(f"episode {ep}: {sum(1 for r in sampled if r['episode'] == ep)}"
                                 for ep in sorted(by_episode)))
    return sampled


def make_client(provider: str):
    cfg = rag.PROVIDERS[provider]
    api_key = os.environ.get(cfg["api_key_env"], "")
    if not api_key:
        raise RuntimeError(f"{cfg['api_key_env']} is not set. Add it to .env")
    from openai import OpenAI
    base_url = os.environ.get(cfg["base_url_env"], cfg["base_url_default"])
    return OpenAI(api_key=api_key, base_url=base_url, timeout=120)


def judge(client, model: str, question: str, answer_orig: str, answer_llm: str,
          max_retries: int = 3, temperature: float | None = None):
    """Call the judge once; returns (AnswerEvaluation, usage).

    temperature is omitted when None: newer models (gpt-5.6 line) reject any
    temperature value other than the default.
    """
    messages = [
        {"role": "system", "content": JUDGE_INSTRUCTIONS},
        {"role": "user", "content": JUDGE_PROMPT.format(
            question=question, answer_orig=answer_orig, answer_llm=answer_llm)},
    ]
    kwargs: dict = {"model": model, "messages": messages,
                    "response_format": AnswerEvaluation}
    if temperature is not None:
        kwargs["temperature"] = temperature
    for attempt in range(max_retries):
        try:
            resp = client.beta.chat.completions.parse(**kwargs)
            parsed = resp.choices[0].message.parsed
            if parsed is None or parsed.score not in ("good", "bad"):
                raise RuntimeError(f"unexpected judge output: {parsed!r}")
            return parsed, resp.usage
        except Exception:
            if attempt == max_retries - 1:
                raise
            time.sleep(2 ** attempt)
    raise RuntimeError("unreachable")


def _usage_dict(usage) -> dict:
    if usage is None:
        return {}
    # openai returns a pydantic model; some providers (e.g. deepseek) return a plain dict
    d = usage.model_dump() if hasattr(usage, "model_dump") else usage
    return {k: d.get(k) for k in ("prompt_tokens", "completion_tokens", "total_tokens")}


def _add_usage(total: dict, usage: dict) -> None:
    for k in ("prompt_tokens", "completion_tokens", "total_tokens"):
        total[k] = total.get(k, 0) + (usage.get(k) or 0)


def evaluate(rec: dict, answer_model: str, index, embed, clients: dict,
             judge_model: str, backend: str, top_k: int,
             judge_temperature: float | None = None,
             reranker=None, rerank_candidates: int = 20,
             retrieve_query: str | None = None) -> dict:
    """One (record, answer_model) pair: RAG answer + judge verdict."""
    entry = {
        "faq_id": rec["faq_id"],
        "episode": rec["episode"],
        "question": rec["question"],
        "retrieve_query": retrieve_query,
        "answer_orig": rec["answer"],
        "answer_llm": None,
        "answer_model": answer_model,
        "judge_model": judge_model,
        "score": "failed",
        "reasoning": None,
        "error": None,
        "tokens": {"prompt_tokens": 0, "completion_tokens": 0, "total_tokens": 0},
    }
    try:
        result = rag.answer(
            rec["question"], backend=backend, top_k=top_k, model=answer_model,
            index=index, embed=embed, reranker=reranker,
            rerank_candidates=rerank_candidates,
            client=clients[rag.resolve_provider(None, answer_model)],
            retrieve_query=retrieve_query,
        )
    except Exception as exc:
        entry["error"] = f"rag: {exc}"
        return entry
    if result.get("error"):
        entry["error"] = f"rag: {result['error']}"
        return entry
    entry["answer_llm"] = result["raw"]
    _add_usage(entry["tokens"], _usage_dict(result.get("usage")))

    try:
        verdict, usage = judge(
            clients["openai"], judge_model,
            rec["question"], rec["answer"], result["raw"],
            temperature=judge_temperature,
        )
    except Exception as exc:
        entry["error"] = f"judge: {exc}"
        return entry
    _add_usage(entry["tokens"], _usage_dict(usage))
    entry["score"] = verdict.score
    entry["reasoning"] = verdict.reasoning
    return entry


def summary_table(details: list[dict], answer_models: list[str]) -> dict:
    summary: dict = {}
    for am in answer_models:
        rows = [d for d in details if d["answer_model"] == am]
        good = sum(1 for r in rows if r["score"] == "good")
        bad = sum(1 for r in rows if r["score"] == "bad")
        failed = sum(1 for r in rows if r.get("error"))
        summary[am] = {
            "total": len(rows),
            "good": good,
            "bad": bad,
            "failed": failed,
            "good_rate": (good / len(rows)) if rows else None,
        }
    return summary


def best_answer_model(details: list[dict]) -> str | None:
    """Best model by good rate; ties broken by model name."""
    by_model: dict = {}
    for d in details:
        by_model.setdefault(d["answer_model"], []).append(d)
    if not by_model:
        return None
    best, best_key = None, None
    for am, rows in by_model.items():
        good = sum(1 for r in rows if r["score"] == "good")
        rate = good / len(rows)
        key = (rate, am)
        if best_key is None or key > best_key:
            best, best_key = am, key
    return best


def set_env_default(model: str, env_path: Path | None = None) -> Path:
    """Set 05_MODEL=<model> in .env (create the key if missing)."""
    path = env_path or PROJECT_ROOT / ".env"
    text = path.read_text(encoding="utf-8-sig") if path.exists() else ""
    lines = text.splitlines()
    out, found = [], False
    for line in lines:
        if line.strip().startswith("05_MODEL="):
            out.append(f"05_MODEL={model}")
            found = True
        else:
            out.append(line)
    if not found:
        if out and out[-1].strip() != "":
            out.append("")
        out.append(f"05_MODEL={model}")
    path.write_text("\n".join(out) + ("\n" if out else ""), encoding="utf-8")
    return path


def _q_hash(question: str) -> str:
    import hashlib
    return hashlib.sha1(question.encode("utf-8")).hexdigest()


def load_rewrites(path: Path) -> dict:
    if not path.exists():
        return {}
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
        return data if isinstance(data, dict) else {}
    except (json.JSONDecodeError, OSError):
        return {}


def save_rewrites(path: Path, model: str, items: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps({"rewrite_model": model, "items": items},
                               ensure_ascii=False, indent=2), encoding="utf-8")


def compatible(saved: dict, judge_model: str, backend: str, top_k: int,
               rerank_model: str | None, rewrite_mode: str,
               rewrite_model: str) -> bool:
    # Results accumulate per (faq_id, answer_model); only retrieval/backend,
    # judge, rerank and rewrite config invalidate the checkpoint. Question
    # set, sample size and the answer-model list may change freely.
    return (saved.get("backend") == backend
            and saved.get("top_k") == top_k
            and saved.get("judge_model") == judge_model
            and saved.get("rerank_model") == rerank_model
            and saved.get("rewrite_mode") == rewrite_mode
            and saved.get("rewrite_model") == rewrite_model)


def save(out_path: Path, meta: dict, records: list[dict],
         details: list[dict], answer_models: list[str]) -> None:
    out_path.parent.mkdir(parents=True, exist_ok=True)
    present = sorted({d["answer_model"] for d in details})
    payload = {
        **meta,
        "answer_models": present or answer_models,
        "num_queries_done": len(details),
        "summary": summary_table(details, present or answer_models),
        "details": details,
    }
    out_path.write_text(json.dumps(payload, ensure_ascii=False, indent=2),
                        encoding="utf-8")


def print_summary(details: list[dict], answer_models: list[str],
                  show_bad: int) -> None:
    summary = summary_table(details, answer_models)
    print()
    print(f"{'answer model':<22} {'good':>4} {'bad':>4} {'failed':>6} "
          f"{'good_rate':>9}")
    best, best_rate = None, -1.0
    for am, s in summary.items():
        rate = s["good_rate"]
        if rate is not None and rate > best_rate:
            best, best_rate = am, rate
        rate_str = f"{rate:.1%}" if rate is not None else "n/a"
        print(f"{am:<22} {s['good']:>4} {s['bad']:>4} {s['failed']:>6} "
              f"{rate_str:>9}")
    if best:
        print(f"\nbest answer model: {best} ({best_rate:.1%} good)")

    bad_rows = [d for d in details if d["score"] == "bad"]
    if bad_rows and show_bad > 0:
        print(f"\nbad cases ({len(bad_rows)} total, showing {min(show_bad, len(bad_rows))}):")
        for d in bad_rows[:show_bad]:
            print(f"  [{d['answer_model']}] {d['question'][:90]}")
            print(f"    reasoning: {d['reasoning']}")


def default_out_name(backend: str, top_k: int, judge_model: str,
                    rerank_model: str | None, rewrite_mode: str,
                    rewrite_model: str, sample: int) -> str:
    """Auto-named results file so different configs never overwrite each other."""
    b = "es" if backend == "elasticsearch" else "mem"
    name = f"rag_eval_{b}_k{top_k}"
    name += f"_rw-{rewrite_model}" if rewrite_mode == "llm" else "_norw"
    if rerank_model:
        name += "_rerank-" + rerank_model.replace("/", "-")
    name += "_judge-" + judge_model
    if sample:
        name += f"_s{sample}"
    return name + ".json"


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Evaluate RAG answer quality with an LLM-as-a-judge (A->Q->A').")
    parser.add_argument("--faq", default=str(PROJECT_ROOT / "data/faq"))
    parser.add_argument("--backend", choices=["memory", "elasticsearch"], default="memory")
    parser.add_argument("--top-k", type=int, default=5)
    parser.add_argument("--rerank-model", default=None,
                        help="cross-encoder model to re-rank candidates (e.g. BAAI/bge-reranker-base); empty = off")
    parser.add_argument("--rerank-candidates", type=int, default=20,
                        help="candidates fetched before reranking (default: 20)")
    parser.add_argument("--answer-models", default=None,
                        help="comma-separated models to evaluate (default: 05_MODEL or gpt-4o-mini)")
    parser.add_argument("--judge-model", default=None,
                        help=f"judge model (default: 06_JUDGE_MODEL or {DEFAULT_JUDGE_MODEL})")
    parser.add_argument("--judge-temperature", type=float, default=None,
                        help="judge temperature; omitted by default (required by gpt-5.6 line)")
    parser.add_argument("--rewrite", choices=["none", "llm"], default="llm",
                        help="rewrite questions with an LLM before retrieval (default: llm)")
    parser.add_argument("--rewrite-model", default=None,
                        help=f"rewriter model (default: 06_REWRITE_MODEL or {DEFAULT_REWRITE_MODEL}); "
                             "must NOT be one of the answer models")
    parser.add_argument("--rewrite-cache", default=str(DEFAULT_REWRITE_CACHE),
                        help="cache of rewritten questions keyed by question hash")
    parser.add_argument("--sample", type=int, default=0,
                        help="number of questions to evaluate (0 = all); partial runs use "
                             "stratified random sampling across episodes")
    parser.add_argument("--seed", type=int, default=42, help="random seed for --sample")
    parser.add_argument("--workers", type=int, default=6)
    parser.add_argument("--show-bad", type=int, default=10, help="how many bad cases to print")
    parser.add_argument("--out", default="",
                        help="results file (empty = auto-named by backend/top_k/rewrite/judge/rerank)")
    parser.add_argument("--force", action="store_true", help="ignore the checkpoint and start fresh")
    parser.add_argument("--no-set-default", action="store_true",
                        help="do not write the best model to 05_MODEL in .env")
    args = parser.parse_args()

    answer_models = [m.strip() for m in (args.answer_models or os.environ.get("05_MODEL", "")).split(",") if m.strip()]
    if not answer_models:
        answer_models = [DEFAULT_ANSWER_MODEL]
    judge_model = args.judge_model or os.environ.get("06_JUDGE_MODEL", DEFAULT_JUDGE_MODEL)
    rewrite_mode = args.rewrite
    rewrite_model = args.rewrite_model or os.environ.get("06_REWRITE_MODEL", DEFAULT_REWRITE_MODEL)

    if rewrite_mode == "llm" and rewrite_model in answer_models:
        raise SystemExit(
            f"rewriter model {rewrite_model} is also an answer model - "
            "pick a model outside --answer-models to keep the bake-off fair")

    records = load_faq_records(args.faq)
    if args.sample:
        records = sample_records(records, args.sample, args.seed)
    if not records:
        raise SystemExit(f"No FAQ records found in {args.faq}")

    rewritten: dict[str, str] = {}
    if rewrite_mode == "llm":
        cache_path = Path(args.rewrite_cache)
        cached = load_rewrites(cache_path)
        if cached.get("rewrite_model") != rewrite_model:
            cached = {"rewrite_model": rewrite_model, "items": {}}
        rewritten = dict(cached.get("items", {}))
        unique = {r["question"] for r in records}
        todo_q = [q for q in unique if _q_hash(q) not in rewritten]
        if todo_q:
            print(f"rewriting {len(todo_q)}/{len(unique)} unique questions "
                  f"with {rewrite_model}...")
            rc = make_client("openai")
            for q in tqdm(todo_q):
                rewritten[_q_hash(q)] = rewrite_query(q, rewrite_model, rc)
            save_rewrites(cache_path, rewrite_model, rewritten)
        print(f"rewritten queries: {len(rewritten)} cached -> {cache_path}")

    out_path = Path(args.out) if args.out else \
        PROJECT_ROOT / "data/results" / default_out_name(
            args.backend, args.top_k, judge_model, args.rerank_model,
            rewrite_mode, rewrite_model, args.sample)
    details: list[dict] = []
    print(f"results file: {out_path}")
    if out_path.exists() and not args.force:
        saved = json.loads(out_path.read_text(encoding="utf-8"))
        if compatible(saved, judge_model, args.backend, args.top_k,
                      args.rerank_model, rewrite_mode, rewrite_model):
            details = saved["details"]
        else:
            print("existing checkpoint incompatible (backend/top_k/judge/answer models changed) - starting fresh")

    done = {(d["faq_id"], d["answer_model"]) for d in details
            if d.get("score") in ("good", "bad")}
    todo = [(r, am) for r in records for am in answer_models
            if (r["faq_id"], am) not in done]
    # Drop stale entries (e.g. failed runs) that will be re-evaluated now,
    # otherwise they double-count in the summary below.
    todo_keys = {(r["faq_id"], am) for r, am in todo}
    details = [d for d in details
               if (d.get("faq_id"), d.get("answer_model")) not in todo_keys]
    print(f"records: {len(records)} | answer models: {', '.join(answer_models)} "
          f"| judge: {judge_model} | backend: {args.backend} | top_k: {args.top_k}"
          f" | rewrite: {rewrite_mode}" +
          (f" ({rewrite_model})" if rewrite_mode == "llm" else ""))
    print(f"items: {len(records) * len(answer_models)} total, "
          f"{len(done)} cached, {len(todo)} to evaluate")

    if todo:
        print("building pipeline...")
        index, embed, reranker = rag.build_pipeline(args.backend, rerank_model=args.rerank_model)
        clients: dict = {}
        for am in answer_models:
            provider = rag.resolve_provider(None, am)
            if provider not in clients:
                clients[provider] = make_client(provider)
        if "openai" not in clients:
            clients["openai"] = make_client("openai")  # judge always openai

        meta = {
            "backend": args.backend,
            "top_k": args.top_k,
            "answer_models": answer_models,
            "judge_model": judge_model,
            "rerank_model": args.rerank_model,
            "rewrite_mode": rewrite_mode,
            "rewrite_model": rewrite_model,
            "num_queries_total": len(records),
            "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        }
        with ThreadPoolExecutor(max_workers=args.workers) as pool:
            with tqdm(total=len(todo)) as pbar:
                for i in range(0, len(todo), BATCH):
                    batch = todo[i : i + BATCH]
                    futures = [
                        pool.submit(evaluate, rec, am, index, embed, clients,
                                    judge_model, args.backend, args.top_k,
                                    args.judge_temperature,
                                    reranker, args.rerank_candidates,
                                    rewritten.get(_q_hash(rec["question"])))
                        for rec, am in batch
                    ]
                    for f in futures:
                        details.append(f.result())
                        pbar.update(1)
                    save(out_path, meta, records, details, answer_models)
        print(f"saved results -> {out_path}")

    present = sorted({d["answer_model"] for d in details})
    print_summary(details, present or answer_models, args.show_bad)

    if present and not args.no_set_default:
        best = best_answer_model(details)
        if best:
            set_env_default(best)
            print(f"\ndefault answer model -> 05_MODEL={best} in .env "
                  f"(restart the app to apply)")


if __name__ == "__main__":
    main()
